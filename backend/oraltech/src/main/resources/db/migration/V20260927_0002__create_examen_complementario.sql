-- HU-4 Exámenes Complementarios: sección singleton inmutable (crear-una-vez).
-- Tabla nueva: no afecta filas existentes. Booleanos NOT NULL con DEFAULT FALSE;
-- los textos quedan nulables (solo se exigen cuando su checkbox está marcado).
CREATE TABLE IF NOT EXISTS public.examen_complementario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by CHARACTER VARYING(255),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_by CHARACTER VARYING(255),
    rx_panoramica BOOLEAN NOT NULL DEFAULT FALSE,
    rx_periapical BOOLEAN NOT NULL DEFAULT FALSE,
    rx_periapical_comentario TEXT,
    paquete_ortodoncia BOOLEAN NOT NULL DEFAULT FALSE,
    otros BOOLEAN NOT NULL DEFAULT FALSE,
    otros_texto TEXT,
    historia_clinica_id UUID NOT NULL UNIQUE REFERENCES public.historia_clinica(id)
);
