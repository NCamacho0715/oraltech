-- HU-2 Inmutabilidad con desbloqueo ADMIN: auditoría de cada desbloqueo excepcional
-- (corrección de error de digitación). Tabla solo de escritura: las filas nunca
-- se editan; `usado` marca que el desbloqueo ya se consumió en el siguiente PUT.
CREATE TABLE IF NOT EXISTS public.desbloqueo_seccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by CHARACTER VARYING(255),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_by CHARACTER VARYING(255),
    historia_clinica_id UUID NOT NULL REFERENCES public.historia_clinica(id),
    seccion CHARACTER VARYING(64) NOT NULL,
    motivo TEXT NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_desbloqueo_historia_seccion
    ON public.desbloqueo_seccion (historia_clinica_id, seccion);
